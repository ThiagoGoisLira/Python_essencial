
#Calculo fatorial
def fatorial(n):
    f = 1
    for c in range(1,n+1):
        f *= c
    return f

#Calculo da metade
def metade(num):
    return num/2

#Calculo do dobro
def dobro(n):
    return n * 2

#Calculo Aumentando 10%
def aumentar(n):
    return n * 1.10

#Calculo Diminuir 13%
def diminuir(n):
    return n * 0.87

#Calculo do tripo
def triplo(n):
    return n * 3

